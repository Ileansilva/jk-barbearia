create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null,
  description text default '',
  price numeric(10,2) not null default 0 check (price >= 0),
  duration_minutes integer not null default 30 check (duration_minutes >= 10),
  image_url text,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  id integer primary key default 1 check (id = 1),
  business_name text not null default 'JK Barbearia',
  phone text default '',
  instagram text default '',
  address text default '',
  open_time time not null default '08:00',
  close_time time not null default '19:00',
  slot_interval_minutes integer not null default 30 check (slot_interval_minutes between 15 and 180),
  work_days integer[] not null default array[1,2,3,4,5,6],
  blocked_dates date[] not null default '{}',
  updated_at timestamptz not null default now()
);

insert into public.settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  protocol uuid not null default gen_random_uuid(),
  client_name text not null check (char_length(client_name) between 2 and 80),
  phone text not null check (char_length(phone) between 8 and 25),
  service_id bigint references public.services(id) on delete restrict,
  service_name text not null,
  price numeric(10,2) not null default 0,
  booking_date date not null,
  booking_time time not null,
  notes text default '',
  status text not null default 'confirmado' check (status in ('confirmado','concluido','cancelado')),
  created_at timestamptz not null default now()
);

-- Impede dois agendamentos ativos no mesmo horário.
create unique index if not exists bookings_unique_active_slot
on public.bookings (booking_date, booking_time)
where status <> 'cancelado';

