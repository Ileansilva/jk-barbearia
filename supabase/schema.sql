-- Retorna apenas os horários ocupados, sem revelar nome/telefone.
create or replace function public.get_booked_times(p_date date)
returns table(booked_time time)
language sql
security definer
set search_path = public
as $$
  select b.booking_time
  from public.bookings b
  where b.booking_date = p_date
    and b.status <> 'cancelado';
$$;

revoke all on function public.get_booked_times(date) from public;
grant execute on function public.get_booked_times(date) to anon, authenticated;

-- Cria o agendamento de forma segura e retorna o protocolo.
create or replace function public.create_booking(
  p_client_name text,
  p_phone text,
  p_service_id bigint,
  p_booking_date date,
  p_booking_time time,
  p_notes text default ''
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.services%rowtype;
  cfg public.settings%rowtype;
  new_protocol uuid;
  weekday integer;
begin
  select * into s from public.services where id = p_service_id and active = true;
  if not found then raise exception 'Serviço inválido ou indisponível.'; end if;

  select * into cfg from public.settings where id = 1;

  if p_booking_date < current_date then raise exception 'Não é possível agendar uma data passada.'; end if;

  weekday := extract(dow from p_booking_date)::integer;
  if not (weekday = any(cfg.work_days)) then raise exception 'A barbearia não atende neste dia.'; end if;

  if p_booking_date = any(cfg.blocked_dates) then raise exception 'Esta data está bloqueada.'; end if;

  if p_booking_time < cfg.open_time or p_booking_time >= cfg.close_time then
    raise exception 'Horário fora do expediente.';
  end if;

  insert into public.bookings(client_name,phone,service_id,service_name,price,booking_date,booking_time,notes)
  values(trim(p_client_name),trim(p_phone),s.id,s.name,s.price,p_booking_date,p_booking_time,left(coalesce(p_notes,''),250))
  returning protocol into new_protocol;

  return new_protocol;
exception
  when unique_violation then
    raise exception 'Este horário já foi reservado. Escolha outro.';
end;
$$;

revoke all on function public.create_booking(text,text,bigint,date,time,text) from public;
grant execute on function public.create_booking(text,text,bigint,date,time,text) to anon, authenticated;

